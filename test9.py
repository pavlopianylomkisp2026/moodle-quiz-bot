
import re


# ---------------------------------------------------------
# Допоміжні функції
# ---------------------------------------------------------

def hex_to_bin(value):
    """Перетворює HEX число у 12-бітний двійковий рядок."""
    return format(int(value, 16), "012b")


def bin_to_hex(value):
    """Перетворює двійковий рядок у HEX."""
    return format(int(value, 2), "03X")


def change_bit(value, bit_number, forced_value):
    """
    Примусово встановлює заданий біт у 0 або 1.

    B0/S0 — молодший біт (справа).
    B11/S11 — старший біт.
    """

    mask = 1 << bit_number

    if forced_value == 1:
        value |= mask
    else:
        value &= ~mask

    return value


# ---------------------------------------------------------
# Основний алгоритм
# ---------------------------------------------------------

def solve_question(question):

    # -----------------------------------------------------
    # 1. Знаходимо числа A і B
    # -----------------------------------------------------

    match = re.search(
        r"додаваня\s+([0-9A-Fa-f]+)\s+\(на вході A\)\s+і\s+([0-9A-Fa-f]+)\s+\(на вході B\)",
        question,
        re.IGNORECASE
    )

    if not match:
        # Запасний варіант написання
        match = re.search(
            r"додаваня\s+([0-9A-Fa-f]+).*?і\s+([0-9A-Fa-f]+).*?вході B",
            question,
            re.IGNORECASE
        )

    if not match:
        raise ValueError("Не вдалося знайти числа A та B.")

    a_hex = match.group(1).upper()
    b_hex = match.group(2).upper()

    a = int(a_hex, 16)
    b = int(b_hex, 16)

    # -----------------------------------------------------
    # 2. Знаходимо несправний сигнал
    # -----------------------------------------------------

    fault_match = re.search(
        r"(вхід|вихід)\s+([BS])(\d+).*?(?:на\s+землю\s+\(на\s+['\"]?0['\"]?\)|"
        r"на\s+['\"]?0['\"]?\s+закорочений|"
        r"на\s+живлення\s+\(на\s+['\"]?1['\"]?\)|"
        r"на\s+['\"]?1['\"]?\s+закорочений)",
        question,
        re.IGNORECASE
    )

    if not fault_match:
        raise ValueError("Не вдалося знайти несправний біт.")

    signal_type = fault_match.group(2).upper()
    bit_number = int(fault_match.group(3))

    # -----------------------------------------------------
    # 3. Визначаємо, на 0 чи на 1 закорочений сигнал
    # -----------------------------------------------------

    if re.search(r"на\s+землю\s+\(на\s+['\"]?0['\"]?\)", question, re.IGNORECASE):
        forced_value = 0

    elif re.search(r"на\s+['\"]?0['\"]?\s+закорочений", question, re.IGNORECASE):
        forced_value = 0

    elif re.search(r"на\s+живлення\s+\(на\s+['\"]?1['\"]?\)", question, re.IGNORECASE):
        forced_value = 1

    elif re.search(r"на\s+['\"]?1['\"]?\s+закорочений", question, re.IGNORECASE):
        forced_value = 1

    else:
        raise ValueError("Не вдалося визначити значення закорочення.")

    # -----------------------------------------------------
    # 4. Застосовуємо несправність
    # -----------------------------------------------------

    if signal_type == "B":
        # Несправність на вході B
        b = change_bit(b, bit_number, forced_value)

    elif signal_type == "S":
        # Несправність на виході S
        # Спочатку виконаємо нормальне додавання.
        pass

    # -----------------------------------------------------
    # 5. Додавання
    # -----------------------------------------------------

    r = a + b

    # -----------------------------------------------------
    # 6. Якщо пошкоджений вихід S, змінюємо відповідний біт
    # -----------------------------------------------------

    if signal_type == "S":
        r = change_bit(r, bit_number, forced_value)

    # -----------------------------------------------------
    # 7. R mod 15
    # -----------------------------------------------------

    result = r % 15

    # -----------------------------------------------------
    # 8. Вивід
    # -----------------------------------------------------

    return format(result, "X")


# ---------------------------------------------------------
# Програма
# ---------------------------------------------------------

print("Введіть питання:")
question = input("> ")

try:
    answer = solve_question(question)

    print()
    print("Правильна відповідь:", answer)

except ValueError as error:
    print()
    print("Помилка:", error)

